#!/usr/bin/env bash
# Writes snapshot.js: the issue states index.html falls back to when it cannot
# reach the GitHub API (offline, or past the 60 requests an hour without a token).
set -euo pipefail

cd "$(dirname "$0")"

{
  printf '// Generated by refresh-snapshot.sh. Do not edit by hand.\n'
  printf 'window.ISSUE_SNAPSHOT = '
  gh issue list --repo jennifermhansson/ticket-booking-platform --state all --limit 500 \
    --json number,title,state,assignees,milestone |
    jq '{
      takenAt: (now | todate),
      issues: (map({
        key: (.number | tostring),
        value: {
          title,
          state: (.state | ascii_downcase),
          assignees: [.assignees[].login],
          milestone: .milestone.title
        }
      }) | from_entries)
    }'
} > snapshot.js
